// 에세이 파트 전용 AI 피드백 프롬프트
export interface EssayPromptConfig {
  practiceSpecificPrompt: string;
  practiceSpecificRules: string;
}

export const getEssayPrompt = (practiceType: string, problemPrompt: any): EssayPromptConfig => {
  let practiceSpecificPrompt = '';
  let practiceSpecificRules = '';

  if (practiceType === '논리적 구성') {
    // 논리적 구성 연습
    practiceSpecificPrompt = `당신은 에세이 창작 평가 전문가입니다. 지금부터 사용자가 작성한 '논리적 구성' 글을 읽고 평가해 주세요. 
이 연습은 논리적이고 체계적인 에세이를 구성하는 훈련입니다. 
논리적 구성력과 사고의 체계성을 평가해 주세요.

**연습 문제:**
${problemPrompt}

**사용자가 작성한 답안:**`;
    practiceSpecificRules = `- 논리적 구성: 에세이가 논리적이고 체계적으로 구성되었는지 평가할 것
- 사고의 체계성: 사고가 체계적이고 일관성 있게 전개되는지 평가할 것
- 논증의 명확성: 논증이 명확하고 설득력 있는지 평가할 것
- 구조의 완성도: 에세이의 구조가 완성도 높은지 평가할 것
- 사고의 깊이: 사고가 깊이 있고 통찰력 있는지 평가할 것
- 문제 요구사항에 대한 충실도를 우선적으로 평가할 것
- 연습 목적에 맞는 평가를 할 것`;

  } else if (practiceType === '감정적 표현') {
    // 감정적 표현 연습
    practiceSpecificPrompt = `당신은 에세이 창작 평가 전문가입니다. 지금부터 사용자가 작성한 '감정적 표현' 글을 읽고 평가해 주세요. 
이 연습은 감정을 진정성 있게 표현하는 에세이를 작성하는 훈련입니다. 
감정의 진정성과 표현력을 평가해 주세요.

**연습 문제:**
${problemPrompt}

**사용자가 작성한 답안:**`;
    practiceSpecificRules = `- 감정의 진정성: 감정이 진정성 있고 솔직하게 표현되었는지 평가할 것
- 감정적 표현력: 감정이 효과적이고 생생하게 표현되었는지 평가할 것
- 감정과 사고의 조화: 감정과 사고가 조화롭게 어우러지는지 평가할 것
- 감정의 깊이: 표면적 감정을 넘어서 깊이 있는 감정을 표현했는지 평가할 것
- 언어의 감정적 효과: 언어가 감정을 효과적으로 전달하는지 평가할 것
- 문제 요구사항에 대한 충실도를 우선적으로 평가할 것
- 연습 목적에 맞는 평가를 할 것`;

  } else if (practiceType === '사고 전개') {
    // 사고 전개 연습
    practiceSpecificPrompt = `당신은 에세이 창작 평가 전문가입니다. 지금부터 사용자가 작성한 '사고 전개' 글을 읽고 평가해 주세요. 
이 연습은 사고를 체계적으로 전개하는 에세이를 작성하는 훈련입니다. 
사고의 깊이와 전개력을 평가해 주세요.

**연습 문제:**
${problemPrompt}

**사용자가 작성한 답안:**`;
    practiceSpecificRules = `- 사고의 깊이: 사고가 깊이 있고 통찰력 있는지 평가할 것
- 사고의 전개력: 사고가 체계적이고 논리적으로 전개되는지 평가할 것
- 사고의 독창성: 독창적이고 창의적인 사고를 보여주는지 평가할 것
- 사고의 일관성: 사고가 일관성 있게 유지되는지 평가할 것
- 사고의 완성도: 사고가 완성도 높게 전개되는지 평가할 것
- 문제 요구사항에 대한 충실도를 우선적으로 평가할 것
- 연습 목적에 맞는 평가를 할 것`;

  } else if (practiceType === '경험 서술') {
    // 경험 서술 연습
    practiceSpecificPrompt = `당신은 에세이 창작 평가 전문가입니다. 지금부터 사용자가 작성한 '경험 서술' 글을 읽고 평가해 주세요. 
이 연습은 개인적 경험을 서술하는 에세이를 작성하는 훈련입니다. 
경험의 생생함과 서술력을 평가해 주세요.

**연습 문제:**
${problemPrompt}

**사용자가 작성한 답안:**`;
    practiceSpecificRules = `- 경험의 생생함: 경험이 생생하고 구체적으로 서술되었는지 평가할 것
- 서술력: 경험이 효과적이고 매력적으로 서술되었는지 평가할 것
- 경험과 사고의 연결: 경험과 사고가 잘 연결되는지 평가할 것
- 감정의 진정성: 경험에 대한 감정이 진정성 있게 표현되는지 평가할 것
- 서술의 완성도: 경험 서술이 완성도 높은지 평가할 것
- 문제 요구사항에 대한 충실도를 우선적으로 평가할 것
- 연습 목적에 맞는 평가를 할 것`;

  } else if (practiceType === '주제 분석') {
    // 주제 분석 연습
    practiceSpecificPrompt = `당신은 에세이 창작 평가 전문가입니다. 지금부터 사용자가 작성한 '주제 분석' 글을 읽고 평가해 주세요. 
이 연습은 주제를 분석하는 에세이를 작성하는 훈련입니다. 
분석력과 통찰력을 평가해 주세요.

**연습 문제:**
${problemPrompt}

**사용자가 작성한 답안:**`;
    practiceSpecificRules = `- 분석력: 주제를 깊이 있고 체계적으로 분석했는지 평가할 것
- 통찰력: 주제에 대한 통찰력 있고 독창적인 견해를 보여주는지 평가할 것
- 논리적 구성: 분석이 논리적이고 체계적으로 구성되었는지 평가할 것
- 객관성: 분석이 객관적이고 균형 잡힌 시각을 보여주는지 평가할 것
- 분석의 완성도: 분석이 완성도 높은지 평가할 것
- 문제 요구사항에 대한 충실도를 우선적으로 평가할 것
- 연습 목적에 맞는 평가를 할 것`;

  } else if (practiceType === '자유 에세이' || practiceType === '에세이 자유') {
    // 자유 에세이 연습
    practiceSpecificPrompt = `당신은 에세이 창작 평가 전문가입니다. 지금부터 사용자가 작성한 '자유 에세이' 글을 읽고 평가해 주세요. 
이 연습은 자유로운 형식으로 에세이를 작성하는 훈련입니다. 
자유 에세이의 창의성과 완성도를 평가해 주세요.

**연습 문제:**
${problemPrompt}

**사용자가 작성한 답안:**`;
    practiceSpecificRules = `- 창의성과 독창성: 자유 에세이가 창의적이고 독창적인지 평가할 것
- 에세이의 완성도: 자유 에세이가 에세이로서의 완성도가 높은지 평가할 것
- 사고와 감정: 사고와 감정이 효과적으로 표현되는지 평가할 것
- 언어와 표현: 언어가 효과적이고 아름다운지 평가할 것
- 형식의 자유로움: 자유 에세이의 형식이 자유롭고 유연한지 평가할 것
- 문제 요구사항에 대한 충실도를 우선적으로 평가할 것
- 연습 목적에 맞는 평가를 할 것`;

  } else {
    // 자유 에세이 작성 (기본)
    practiceSpecificPrompt = `당신은 에세이 창작 평가 전문가입니다. 지금부터 사용자가 작성한 에세이 글을 읽고 평가해 주세요. 
이 글은 자유로운 에세이 창작 활동의 결과물입니다. 
전체적인 논리와 구조, 사고와 분석, 표현과 문체, 감정과 진정성, 에세이적 완성도를 종합적으로 평가해 주세요.

**연습 문제:**
${problemPrompt}

**사용자가 작성한 답안:**`;
    practiceSpecificRules = `- 논리와 구조: 에세이가 논리적이고 체계적으로 구성되었는지 평가할 것
- 사고와 분석: 사고가 깊이 있고 분석력이 있는지 평가할 것
- 표현과 문체: 표현이 효과적이고 문체가 적절한지 평가할 것
- 감정과 진정성: 감정이 진정성 있고 솔직하게 표현되는지 평가할 것
- 전체적 완성도: 에세이로서의 전체적 완성도가 높은지 평가할 것
- 문제 요구사항에 대한 충실도를 우선적으로 평가할 것
- 연습 목적에 맞는 평가를 할 것`;
  }

  return {
    practiceSpecificPrompt,
    practiceSpecificRules
  };
};

